### Last Force Failure Reason 8675: The Forcing Error

The **Last Force Failure Reason 8675** is found in the `sys.query_store_plan` view and indicates a specific reason why the database engine failed to force a query plan.

*   **What it is:** Error code 8675 corresponds to the reason `OPTIMIZATION_REPLAY_FAILED`.
*   **What it means:** This is a newer failure reason, primarily seen in SQL Server 2022 and later versions. It means that the system failed to use the "Optimization Replay" script to recreate the desired plan. Instead of just using the XML plan as a guide, Optimization Replay is a more advanced feature that tries to replay the internal steps the optimizer took to arrive at the good plan. The `8675` error tells you this more sophisticated replay process failed.

#### Why Does Plan Forcing Fail?

Even if a plan was generated by SQL Server, forcing it can fail for several reasons. The plan is not a static blueprint but rather a guide, and the optimizer must still be able to verify it's valid. Common failure reasons include:

| Failure Reason Code | Description |
| :--- | :--- |
| **8675 (OPTIMIZATION\_REPLAY\_FAILED)** | The advanced replay script used to recreate the plan failed. |
| **8698 (NO\_PLAN)** | The query processor couldn't produce a plan because the forced plan couldn't be verified as legal for the query. This can happen with complex queries. |
| **8712 (NO\_INDEX)** | An index used in the forced plan has been dropped or is disabled. |
| **8690 (HINT\_CONFLICT)** | The forced plan conflicts with a query hint that has been added to the code. |
| **8691 (SETOPT\_CONFLICT)** | The session settings (like `ANSI_NULLS`) are different from the settings that were present when the original plan was compiled. |

#### What to Do About Failure 8675

When you see `OPTIMIZATION_REPLAY_FAILED`, it means Automatic Plan Correction is trying to force a plan but is repeatedly failing.

1.  **Acknowledge the Failure:** The immediate takeaway is that APRC is not protecting this query. The "good" plan is no longer considered forceable.
2.  **Revert the Plan:** Manually unforce the plan to stop the system from attempting to apply a failing recommendation. This will allow the optimizer to generate a new plan.
    ```sql
    EXEC sp_query_store_unforce_plan @query_id = <your_query_id>, @plan_id = <your_plan_id>;
    ```
3.  **Analyze:** Investigate what might have changed. While a specific cause for replay failure can be hard to pinpoint, it indicates that the conditions under which the "good" plan was created are no longer present, and the engine cannot recreate it.
4.  **Tune Manually:** Examine the "good" plan that the system was trying to force. Can you make the query behave similarly by adding a specific index or query hint? This is often the most stable long-term solution.




